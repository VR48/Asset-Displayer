"""Publish selected Seb master candidates for review; never alter originals.

Usage: python tools/import-seb-masters.py /absolute/path/to/lanternwake
Requires a complete reviewed candidate manifest, not owner/game approval.
"""
from pathlib import Path
from PIL import Image
import hashlib
import io
import json
import re
import sys

root = Path(__file__).resolve().parent.parent
game = Path(sys.argv[1]).resolve()
source_root = game / 'art-source/seb/masters-v1'
manifest = json.loads((source_root / 'master-manifest.json').read_text(encoding='utf-8-sig'))
assert manifest['status'] == 'draft-ready-for-owner-review'
selected = manifest['selected']
assert {s['direction'] for s in selected} == {'front', 'rear', 'left', 'right'} and len(selected) == 4
data = json.loads((root / 'data.json').read_text(encoding='utf-8'))
sha = lambda b: hashlib.sha256(b).hexdigest()
entries = []
labels = {'front': 'Front / down', 'rear': 'Rear / up', 'left': 'Left', 'right': 'Right'}
for offset, item in enumerate(selected):
    direction = item['direction']
    path = source_root / item['file']
    assert path.resolve().parent == source_root.resolve()
    raw = path.read_bytes()
    assert sha(raw) == item['sha256']
    # MJ/ImageGen PNGs are RGB. Add opaque alpha only: never matte, crop, scale,
    # fit or recolor MASTER artwork for review; magenta stays in the image.
    with Image.open(path) as image:
        rgba = image.convert('RGBA')
        width, height = rgba.size
        output = io.BytesIO()
        rgba.save(output, format='PNG')
    payload = output.getvalue()
    frame_sha = sha(payload)
    url = f'assets/{frame_sha}.png'
    (root / url).write_bytes(payload)
    source = dict(provider='Reference' if direction == 'front' else 'ImageGen',
                  sha256=item['sha256'], collection='Seb low-sword MASTER candidates v1')
    if item.get('baseMidjourneyJob'):
        source['origin_mj_job_uuid'] = item['baseMidjourneyJob']
        source['origin_image_index'] = item['baseImageIndex']
    if item.get('revisionParentSha256'):
        source['previous_sha256'] = item['revisionParentSha256']
    caveats = ['Static neutral standing MASTER candidate, not an animation or approval to replace gameplay assets.',
               'Sword belongs to anatomical right hand and hangs low; projector belongs to anatomical left forearm; shield off.',
               'Pure magenta background retained for future cleanup. Review PNG adds opaque alpha without changing RGB pixels.',
               'No runtime anchor, sprite scale, action timing or animation bank has been calibrated.']
    if item.get('revision'):
        caveats.append(f"Revision {item['revision']}: added angular back armor plates, segmented spine and layered lumbar plates. Previous plain-back source is archived locally; review this revised artwork again.")
    if direction == 'front':
        caveats.append('Existing relaxed low-sword source retained unchanged, used by MJ job cbb51156-6c74-4d87-af82-e6c93535b391; original image-generation provider is not asserted.')
    else:
        caveats.append(f"View generated by Midjourney job {item['baseMidjourneyJob']} (image {item['baseImageIndex']}), then repaired with ImageGen under owner-authorized hybrid workflow.")
        caveats.append('Back and side surfaces are proposed design and remain subject to owner review; no newly generated detail is asserted historically approved.')
    if direction == 'left':
        caveats.append('Near arm is anatomical left (projector, empty hand); far arm is anatomical right (low sword).')
    if direction == 'right':
        caveats.append('Near arm is anatomical right (low sword); far arm is anatomical left (projector, empty hand).')
    entries.append(dict(name=f'seb-master-{direction}-low-sword-v1', number=43 + offset,
                        approval_category='06_NEW_CHARACTER_CANDIDATES', media_kind='image',
                        actual_dimensions=[[width, height]], unique_png_files=1,
                        duration_verified_ms=1000, durations=[1000], caveats=caveats,
                        geometry=dict(canvas=[width, height]), source=source,
                        frames=[dict(url=url, sha256=frame_sha, source_frame=1, duration_ms=1000)],
                        usage=dict(character='Seb', action='Standing MASTER reference · low sword',
                                   direction=labels[direction], attacking=False, status='new-feature',
                                   reason='Seb has no existing playable character animation bank. These are new standing references for future animation, not replacements for an existing runtime slot.')))
names = {s['name'] for s in entries}
previous_urls = {f['url'] for s in data['sets'] if s['name'] in names for f in s['frames']}
data['sets'] = [s for s in data['sets'] if s['name'] not in names] + entries
assert len({s['name'] for s in data['sets']}) == len(data['sets'])
assert len({s['number'] for s in data['sets']}) == len(data['sets'])
(root / 'data.json').write_text(json.dumps(data, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
referenced = {f['url'] for s in data['sets'] for f in s['frames']}
for url in previous_urls - referenced:
    assert re.fullmatch(r'assets/[a-f0-9]{64}\.png', url)
    obsolete = (root / url).resolve()
    assert obsolete.parent == (root / 'assets').resolve()
    obsolete.unlink()  # Previous MASTER source stays in the local source archive.
print(json.dumps(dict(imported=len(entries), character='Seb', totalSets=len(data['sets']))))
